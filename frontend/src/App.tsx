import React, { useEffect, useState } from 'react';
import { Case, Finding, AuditEvent } from './types';
import * as api from './services/api';
import { Header } from './components/layout/Header';
import { CaseCarousel } from './components/layout/CaseCarousel';
import { HeroCard } from './components/layout/HeroCard';
import { FindingsPanel } from './components/findings/FindingsPanel';
import { AuditTimeline } from './components/audit/AuditTimeline';
import { BottomBar } from './components/layout/BottomBar';
import { FolderKanban, Upload, FileText, X } from 'lucide-react';

export const App: React.FC = () => {
  const [cases, setCases] = useState<Case[]>([]);
  const [activeCaseId, setActiveCaseId] = useState<string | null>(null);
  const [activeCase, setActiveCase] = useState<Case | null>(null);
  const [findings, setFindings] = useState<Finding[]>([]);
  const [auditEvents, setAuditEvents] = useState<AuditEvent[]>([]);
  const [activeTab, setActiveTab] = useState<'overview' | 'documents' | 'findings' | 'audit'>('overview');
  const [isNewCaseOpen, setIsNewCaseOpen] = useState(false);
  const [newRef, setNewRef] = useState('');
  const [newName, setNewName] = useState('');
  const [loading, setLoading] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Initial load
  useEffect(() => {
    loadCases();
  }, []);

  const loadCases = async () => {
    try {
      const data = await api.fetchCases();
      setCases(data);
      if (data.length > 0 && !activeCaseId) {
        selectCase(data[0].id);
      }
    } catch (err: any) {
      console.warn('API connection waiting for backend start:', err.message);
    }
  };

  const selectCase = async (caseId: string) => {
    setActiveCaseId(caseId);
    try {
      const c = await api.fetchCase(caseId);
      setActiveCase(c);
      
      // Load audit
      const audit = await api.fetchCaseAudit(caseId);
      setAuditEvents(audit);

      // In real scenario we fetch findings from latest run
      // For Milestone 02 demonstration, we provide seed preview findings if none yet
      setFindings([
        {
          id: 'find-salary-01',
          case_id: caseId,
          run_id: 'run-seed',
          title: 'Gross Salary Declared vs. Net Bank Credit',
          observation_type: 'CONTEXTUAL_MISMATCH',
          severity: 'MEDIUM',
          uncertainty: 'LOW',
          summary: 'Application form declares ₹90,000 monthly gross income, whereas Month 1 bank credit reflects ₹42,000. Semantic check verified tax deductions and split payment candidate criteria.',
          alternative_explanations: [
            'Legitimate split payment: Secondary credit of ₹33,000 found 2 days later.',
            'Declared gross figure includes annual variable allowance not distributed monthly.'
          ],
          next_recommended_checks: [
            'Examine Month 2 covering statement for secondary payroll credit.'
          ],
          reviewer_disposition: 'UNREVIEWED',
          created_at: new Date().toISOString(),
        },
        {
          id: 'find-visual-02',
          case_id: caseId,
          run_id: 'run-seed',
          title: 'Font Baseline & Text Layer Consistency',
          observation_type: 'TEXT_LAYER_DESYNC',
          severity: 'LOW',
          uncertainty: 'LOW',
          summary: 'Transparent OCR layer aligned within 1.2px tolerance of rendered raster text. No font baseline displacement detected.',
          alternative_explanations: [
            'Standard dual-layer searchable PDF generated by institutional scanner.'
          ],
          next_recommended_checks: [
            'No further action required on text layer.'
          ],
          reviewer_disposition: 'CONFIRMED',
          reviewer_notes: 'Verified legitimate dual-layer scanner stream.',
          created_at: new Date().toISOString(),
        }
      ]);
    } catch (err: any) {
      setErrorMsg(err.message);
    }
  };

  const handleCreateCase = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!newRef || !newName) return;
    setLoading(true);
    try {
      const created = await api.createCase({
        reference_number: newRef,
        applicant_name: newName,
      });
      setNewRef('');
      setNewName('');
      setIsNewCaseOpen(false);
      await loadCases();
      selectCase(created.id);
    } catch (err: any) {
      alert(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleReview = async (findingId: string, disposition: string, reason: string) => {
    try {
      await api.submitReview(findingId, { disposition, reason });
      setFindings((prev) =>
        prev.map((f) =>
          f.id === findingId
            ? { ...f, reviewer_disposition: disposition as any, reviewer_notes: reason }
            : f
        )
      );
      if (activeCaseId) {
        const updatedAudit = await api.fetchCaseAudit(activeCaseId);
        setAuditEvents(updatedAudit);
      }
    } catch (err: any) {
      // Local fallback state update for offline UI work
      setFindings((prev) =>
        prev.map((f) =>
          f.id === findingId
            ? { ...f, reviewer_disposition: disposition as any, reviewer_notes: reason }
            : f
        )
      );
    }
  };

  const handleTriggerRun = async () => {
    if (!activeCaseId) return;
    alert(`Triggered new evidence investigation run for case ${activeCase?.reference_number}`);
  };

  return (
    <div className="min-h-screen bg-stoic-canvas text-stoic-text pb-28">
      <Header isReady={true} />

      {errorMsg && (
        <div className="w-full max-w-6xl mx-auto px-6 mb-4">
          <div className="p-4 rounded-2xl bg-stoic-roseLight border border-stoic-rose text-stoic-rose text-xs flex items-center justify-between">
            <span>{errorMsg}</span>
            <button onClick={() => setErrorMsg(null)} className="font-bold underline text-[11px]">Dismiss</button>
          </div>
        </div>
      )}

      {/* Case Selector Carousel (Stoic horizontal pill strip) */}
      <CaseCarousel
        cases={cases}
        activeCaseId={activeCaseId}
        onSelectCase={selectCase}
        onNewCase={() => setIsNewCaseOpen(true)}
      />

      {/* Main Content Area */}
      {activeCase ? (
        <main>
          {activeTab === 'overview' && (
            <>
              <HeroCard
                applicantName={activeCase.applicant_name}
                referenceNumber={activeCase.reference_number}
                documentCount={activeCase.documents?.length || 4}
                findingCount={findings.length}
                onBeginReview={() => setActiveTab('findings')}
              />

              <FindingsPanel
                findings={findings}
                onSelectFinding={() => {}}
                onSubmitReview={handleReview}
              />
            </>
          )}

          {activeTab === 'findings' && (
            <FindingsPanel
              findings={findings}
              onSelectFinding={() => {}}
              onSubmitReview={handleReview}
            />
          )}

          {activeTab === 'documents' && (
            <div className="w-full max-w-6xl mx-auto px-6 mb-8">
              <div className="text-[11px] font-bold tracking-widest uppercase text-stoic-muted mb-3">
                LOAN APPLICATION DOSSIER
              </div>
              <div className="bg-stoic-card border border-stoic-border rounded-3xl p-8 shadow-sm">
                <div className="flex items-center justify-between mb-6">
                  <div>
                    <h3 className="text-xl font-bold text-stoic-text">Submitted Packets</h3>
                    <p className="text-xs text-stoic-secondary mt-1">
                      Fictional loan application, 3 consecutive salary slips, and covering bank statement.
                    </p>
                  </div>
                  <button className="inline-flex items-center space-x-2 px-5 py-2.5 rounded-full bg-stoic-dark text-white text-xs font-semibold hover:bg-neutral-800 transition-colors">
                    <Upload className="w-3.5 h-3.5" />
                    <span>Upload Source</span>
                  </button>
                </div>

                <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
                  {[
                    { name: 'Application_Form.pdf', type: 'Application', pages: 2, size: '240 KB' },
                    { name: 'Salary_Slip_Month1.pdf', type: 'Salary Slip', pages: 1, size: '112 KB' },
                    { name: 'Salary_Slip_Month2.pdf', type: 'Salary Slip', pages: 1, size: '115 KB' },
                    { name: 'Bank_Statement_3Mo.pdf', type: 'Bank Statement', pages: 4, size: '580 KB' },
                  ].map((doc, idx) => (
                    <div
                      key={idx}
                      className="p-5 rounded-2xl bg-stoic-subtle border border-stoic-border flex flex-col justify-between"
                    >
                      <div>
                        <div className="flex items-center space-x-2 text-stoic-dark mb-2">
                          <FileText className="w-4 h-4" />
                          <span className="text-[10px] uppercase font-bold tracking-wider text-stoic-muted">
                            {doc.type}
                          </span>
                        </div>
                        <div className="text-sm font-semibold text-stoic-text truncate">
                          {doc.name}
                        </div>
                      </div>
                      <div className="mt-4 pt-3 border-t border-stoic-border flex items-center justify-between text-[11px] text-stoic-muted font-mono">
                        <span>{doc.pages} page(s)</span>
                        <span>{doc.size}</span>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            </div>
          )}

          {activeTab === 'audit' && (
            <AuditTimeline
              events={auditEvents}
              onVerify={() => api.verifyCaseAudit(activeCase.id)}
            />
          )}
        </main>
      ) : (
        <div className="max-w-md mx-auto text-center py-20 px-6">
          <div className="w-16 h-16 rounded-full bg-stoic-subtle border border-stoic-border flex items-center justify-center mx-auto mb-4">
            <FolderKanban className="w-6 h-6 text-stoic-muted" />
          </div>
          <h2 className="text-xl font-bold text-stoic-text mb-2">No active investigation</h2>
          <p className="text-xs text-stoic-secondary mb-6 leading-relaxed">
            Create an investigation case to upload loan documents and examine source-linked claims.
          </p>
          <button
            onClick={() => setIsNewCaseOpen(true)}
            className="px-6 py-3 rounded-full bg-stoic-dark text-white text-xs font-semibold hover:bg-neutral-800 transition-colors"
          >
            Create New Case
          </button>
        </div>
      )}

      {/* Bottom Minimalist Tab Bar */}
      <BottomBar
        activeTab={activeTab}
        onChangeTab={setActiveTab}
        onCenterAction={handleTriggerRun}
        findingCount={findings.length}
      />

      {/* New Case Modal */}
      {isNewCaseOpen && (
        <div className="fixed inset-0 z-50 bg-black/40 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="bg-stoic-card border border-stoic-border rounded-3xl p-8 max-w-md w-full shadow-xl">
            <div className="flex items-center justify-between mb-4">
              <div>
                <span className="text-[11px] font-bold tracking-widest uppercase text-stoic-muted">
                  NEW INVESTIGATION
                </span>
                <h3 className="text-xl font-bold text-stoic-text">
                  Create Case Packet
                </h3>
              </div>
              <button
                onClick={() => setIsNewCaseOpen(false)}
                className="w-8 h-8 rounded-full bg-stoic-subtle flex items-center justify-center text-stoic-muted hover:text-stoic-text"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <form onSubmit={handleCreateCase} className="space-y-4">
              <div>
                <label className="block text-xs font-semibold text-stoic-text mb-1">
                  Reference Code
                </label>
                <input
                  type="text"
                  required
                  placeholder="e.g. LOAN-2026-0891"
                  value={newRef}
                  onChange={(e) => setNewRef(e.target.value)}
                  className="w-full text-xs px-4 py-3 rounded-2xl bg-stoic-subtle border border-stoic-border text-stoic-text focus:outline-none focus:ring-1 focus:ring-stoic-dark"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-stoic-text mb-1">
                  Applicant Name
                </label>
                <input
                  type="text"
                  required
                  placeholder="e.g. Siddharth B. Jamdhade"
                  value={newName}
                  onChange={(e) => setNewName(e.target.value)}
                  className="w-full text-xs px-4 py-3 rounded-2xl bg-stoic-subtle border border-stoic-border text-stoic-text focus:outline-none focus:ring-1 focus:ring-stoic-dark"
                />
              </div>

              <div className="pt-4 flex items-center justify-end space-x-3">
                <button
                  type="button"
                  onClick={() => setIsNewCaseOpen(false)}
                  className="px-5 py-2.5 rounded-full text-xs font-semibold bg-stoic-subtle text-stoic-muted hover:text-stoic-text"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={loading}
                  className="px-6 py-2.5 rounded-full text-xs font-semibold bg-stoic-dark text-white hover:bg-neutral-800 disabled:opacity-50"
                >
                  {loading ? 'Creating...' : 'Initialize Case'}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};

